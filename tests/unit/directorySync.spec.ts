import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { watchImmediate, type UnwatchFn, type WatchEvent } from '@tauri-apps/plugin-fs'
import { allowPath } from '../../src/lib/fsAccess'
import { perfLog } from '../../src/lib/perfLog'
import { startDirectorySync } from '../../src/lib/directorySync'

vi.mock('@tauri-apps/plugin-fs', () => ({ watchImmediate: vi.fn() }))
vi.mock('../../src/lib/fsAccess', () => ({ allowPath: vi.fn() }))
vi.mock('../../src/lib/perfLog', () => ({ perfLog: vi.fn(async () => {}) }))

const ROOT = 'D:\\notes'
const watch = vi.mocked(watchImmediate)
const authorize = vi.mocked(allowPath)
const stops: ReturnType<typeof vi.fn>[] = []
let disposers: (() => void)[] = []
let visibility: ReturnType<typeof vi.spyOn>

function deferred<T>() {
  let resolve!: (value: T) => void
  let reject!: (reason: unknown) => void
  const promise = new Promise<T>((res, rej) => { resolve = res; reject = rej })
  return { promise, resolve, reject }
}

function install(refresh: () => Promise<void>) {
  const dispose = startDirectorySync(ROOT, refresh)
  disposers.push(dispose)
  return dispose
}

const flush = () => vi.advanceTimersByTimeAsync(0)
const tick = (ms: number) => vi.advanceTimersByTimeAsync(ms)

function emit(paths = [`${ROOT}\\a.md`], type: WatchEvent['type'] = { modify: { kind: 'any' } }, index = watch.mock.calls.length - 1) {
  watch.mock.calls[index][1]({ type, paths, attrs: {} })
}

function changeVisibility(state: DocumentVisibilityState) {
  visibility.mockReturnValue(state)
  // tests/setup.ts replaces document.dispatchEvent; use the real DOM dispatch here.
  EventTarget.prototype.dispatchEvent.call(document, new Event('visibilitychange'))
}

beforeEach(() => {
  vi.useFakeTimers()
  vi.clearAllMocks()
  authorize.mockReset().mockResolvedValue(undefined)
  watch.mockReset().mockImplementation(async () => {
    const stop = vi.fn()
    stops.push(stop)
    return stop
  })
  stops.length = 0
  disposers = []
  visibility = vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
})

afterEach(async () => {
  disposers.forEach((dispose) => dispose())
  await flush()
  vi.restoreAllMocks()
  vi.useRealTimers()
})

describe('directorySync scheduling', () => {
  it('authorizes before recursive native watch and scans after attachment', async () => {
    const authorization = deferred<void>()
    authorize.mockReturnValueOnce(authorization.promise)
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    expect(authorize).toHaveBeenCalledWith(ROOT)
    expect(watch).not.toHaveBeenCalled()
    authorization.resolve(undefined)
    await flush()
    expect(watch).toHaveBeenCalledWith(ROOT, expect.any(Function), { recursive: true })
    expect(refresh).toHaveBeenCalledTimes(1)
    expect(perfLog).toHaveBeenCalledWith(expect.stringContaining('watch started'))
  })

  it('debounces a burst for 300ms after the last dirty event', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    emit()
    await tick(200)
    emit([`${ROOT}\\b.md`], { create: { kind: 'file' } })
    await tick(299)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(refresh).toHaveBeenCalledTimes(1)
    await tick(2_000)
    expect(refresh).toHaveBeenCalledTimes(1)
  })

  it('limits a continuous event stream to a 2-second maximum wait', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    emit()
    for (let i = 0; i < 9; i++) {
      await tick(200)
      emit()
    }
    await tick(199)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(refresh).toHaveBeenCalledTimes(1)
    emit()
    await tick(299)
    expect(refresh).toHaveBeenCalledTimes(1)
    await tick(1)
    expect(refresh).toHaveBeenCalledTimes(2)
  })

  it('serializes refresh and coalesces scan-time dirty events into a follow-up pass', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    const first = deferred<void>()
    const second = deferred<void>()
    refresh.mockReturnValueOnce(first.promise).mockReturnValueOnce(second.promise)
    emit()
    await tick(300)
    emit()
    emit()
    await tick(3_000)
    expect(refresh).toHaveBeenCalledTimes(1)
    first.resolve(undefined)
    await flush()
    expect(refresh).toHaveBeenCalledTimes(2)
    emit()
    second.resolve(undefined)
    await flush()
    expect(refresh).toHaveBeenCalledTimes(3)
  })

  it('reconciles and rebuilds every foreground minute even without native events', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    await tick(59_999)
    expect(refresh).not.toHaveBeenCalled()
    expect(watch).toHaveBeenCalledTimes(1)
    expect(stops[0]).not.toHaveBeenCalled()
    await tick(1)
    // Reconcile immediately, then scan again to close the replacement startup gap.
    expect(refresh).toHaveBeenCalledTimes(2)
    expect(watch).toHaveBeenCalledTimes(2)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(stops[1]).not.toHaveBeenCalled()
    await tick(60_000)
    expect(refresh).toHaveBeenCalledTimes(4)
    expect(watch).toHaveBeenCalledTimes(3)
    expect(authorize).toHaveBeenCalledTimes(3)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(stops[1]).toHaveBeenCalledTimes(1)
    expect(stops[2]).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(1)
  })

  it('recovers a silently detached watcher after root replacement without focus', async () => {
    let rootIdentity = {}
    let notifyCurrentRoot = () => {}
    watch.mockImplementation(async (_path, callback) => {
      const watchedRoot = rootIdentity
      notifyCurrentRoot = () => {
        // A native watch may remain attached to the deleted/moved root object.
        if (watchedRoot === rootIdentity) {
          callback({ type: { create: { kind: 'file' } }, paths: [`${ROOT}\\new.md`], attrs: {} })
        }
      }
      const stop = vi.fn()
      stops.push(stop)
      return stop
    })
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    // Recreate the same path without errors/events being delivered to JavaScript.
    rootIdentity = {}
    notifyCurrentRoot()
    await tick(300)
    expect(refresh).not.toHaveBeenCalled()
    expect(watch).toHaveBeenCalledTimes(1)
    await tick(59_700)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(watch).toHaveBeenCalledTimes(2)
    expect(refresh).toHaveBeenCalledTimes(2)
    refresh.mockClear()
    notifyCurrentRoot()
    await tick(299)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(refresh).toHaveBeenCalledTimes(1)
  })

  it('invalidates callbacks from a periodically retired watcher', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    await tick(60_000)
    refresh.mockClear()
    emit(undefined, undefined, 0)
    await tick(300)
    expect(refresh).not.toHaveBeenCalled()
    emit(undefined, undefined, 1)
    await tick(299)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(refresh).toHaveBeenCalledTimes(1)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(stops[1]).not.toHaveBeenCalled()
  })

  it('does not overlap a slow scan with a reconciliation scan', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    const scan = deferred<void>()
    refresh.mockReturnValueOnce(scan.promise)
    emit()
    await tick(300)
    await tick(60_000)
    expect(refresh).toHaveBeenCalledTimes(1)
    scan.resolve(undefined)
    await flush()
    expect(refresh).toHaveBeenCalledTimes(2)
  })

  it('logs scan failures without hot-looping and retries on the next event', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear().mockRejectedValueOnce(new Error('scan failed'))
    emit()
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(1)
    expect(perfLog).toHaveBeenCalledWith(expect.stringContaining('refresh failed'))
    await tick(3_000)
    expect(refresh).toHaveBeenCalledTimes(1)
    emit()
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(2)
  })
})

describe('directorySync event filtering', () => {
  it('ignores access and access-time metadata, including scan-generated events', async () => {
    const refresh = vi.fn(async () => {
      if (watch.mock.calls.length) emit([ROOT], { access: { kind: 'open', mode: 'read' } })
    })
    install(refresh)
    await flush()
    refresh.mockClear()
    emit([ROOT], { access: { kind: 'close', mode: 'write' } })
    emit([], { access: { kind: 'any' } })
    emit([`${ROOT}\\a.md`], { modify: { kind: 'metadata', mode: 'access-time' } })
    await tick(2_000)
    expect(refresh).not.toHaveBeenCalled()
    emit()
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(1)
  })

  it('ignores only known mutations entirely within dot-name/node_modules subtrees', async () => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    emit([`${ROOT}\\.git\\index`])
    emit([`${ROOT}\\.hidden`], { create: { kind: 'file' } })
    emit([`${ROOT}\\nested\\node_modules\\pkg\\a.md`], { remove: { kind: 'file' } })
    emit([`${ROOT}\\nested\\.hidden\\a.md`, `${ROOT}\\node_modules\\pkg.md`])
    await tick(2_000)
    expect(refresh).not.toHaveBeenCalled()
    emit([`${ROOT}\\node_modules-notes\\a.md`])
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(1)
  })

  it.each([
    ['root', [ROOT], { remove: { kind: 'folder' } }],
    ['empty paths', [], { modify: { kind: 'any' } }],
    ['unknown any', [`${ROOT}\\.hidden`], 'any'],
    ['unknown other', [`${ROOT}\\node_modules\\a.md`], 'other'],
    ['mixed rename', [`${ROOT}\\.hidden`, `${ROOT}\\visible.md`], { modify: { kind: 'rename', mode: 'both' } }],
    ['outside root', ['D:\\notes-other\\.hidden'], { modify: { kind: 'any' } }],
    ['relative ambiguity', ['.hidden'], { modify: { kind: 'any' } }],
    ['parent ambiguity', [`${ROOT}\\.hidden\\..\\visible.md`], { modify: { kind: 'any' } }],
  ] as [string, string[], WatchEvent['type']][])('refreshes %s rather than guessing tree operations', async (_name, paths, type) => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    emit(paths, type)
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(1)
  })

  it('normalizes Windows root case, separators and extended paths before exclusions', async () => {
    const refresh = vi.fn(async () => {})
    disposers.push(startDirectorySync('D:\\Notes\\', refresh))
    await flush()
    refresh.mockClear()
    emit(['d:/notes/node_modules/a.md'])
    emit(['\\\\?\\D:\\NOTES\\.hidden\\a.md'])
    await tick(300)
    expect(refresh).not.toHaveBeenCalled()
    emit(['d:/notes/a.md'])
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(1)
  })

  it('does not treat a hidden workspace root itself as an excluded child', async () => {
    const refresh = vi.fn(async () => {})
    disposers.push(startDirectorySync('D:\\.notes', refresh))
    await flush()
    refresh.mockClear()
    emit(['D:\\.notes\\a.md'])
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(1)
  })
})

describe('directorySync fallback and cleanup', () => {
  it('polls and retries watch every 10 seconds until watch recovers', async () => {
    watch.mockRejectedValueOnce(new Error('watch unsupported'))
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    expect(refresh).toHaveBeenCalledTimes(1)
    expect(perfLog).toHaveBeenCalledWith(expect.stringContaining('watch degraded'))
    refresh.mockClear()
    await tick(9_999)
    expect(watch).toHaveBeenCalledTimes(1)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(watch).toHaveBeenCalledTimes(2)
    expect(authorize).toHaveBeenCalledTimes(2)
    expect(refresh).toHaveBeenCalled()
    refresh.mockClear()
    await tick(59_999)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(refresh).toHaveBeenCalledTimes(2)
    expect(watch).toHaveBeenCalledTimes(3)
  })

  it('retries a failed periodic rebuild after 10 seconds when the root returns without focus', async () => {
    let rootAvailable = true
    watch.mockImplementation(async () => {
      if (!rootAvailable) throw new Error('root missing')
      const stop = vi.fn()
      stops.push(stop)
      return stop
    })
    const refresh = vi.fn(async () => {
      if (!rootAvailable) throw new Error('root missing')
    })
    install(refresh)
    await flush()
    refresh.mockClear()
    rootAvailable = false
    await tick(60_000)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(watch).toHaveBeenCalledTimes(2)
    expect(refresh).toHaveBeenCalledTimes(2)
    expect(perfLog).toHaveBeenCalledWith(expect.stringContaining('watch degraded'))
    refresh.mockClear()
    rootAvailable = true
    emit(undefined, undefined, 0)
    await tick(9_999)
    expect(watch).toHaveBeenCalledTimes(2)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(watch).toHaveBeenCalledTimes(3)
    expect(authorize).toHaveBeenCalledTimes(3)
    expect(refresh).toHaveBeenCalledTimes(2)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(stops[1]).not.toHaveBeenCalled()
    refresh.mockClear()
    emit()
    await tick(300)
    expect(refresh).toHaveBeenCalledTimes(1)
    refresh.mockClear()
    await tick(59_699)
    expect(watch).toHaveBeenCalledTimes(3)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(watch).toHaveBeenCalledTimes(4)
    expect(refresh).toHaveBeenCalledTimes(2)
  })

  it.each(['authorization', 'native attachment'])('keeps a slow periodic %s across maintenance and wake ticks without duplicate starts', async (stage) => {
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    refresh.mockClear()
    const authorization = deferred<void>()
    const attachment = deferred<UnwatchFn>()
    const replacementStop = vi.fn()
    if (stage === 'authorization') {
      authorize.mockReturnValueOnce(authorization.promise)
      watch.mockResolvedValueOnce(replacementStop)
    } else {
      watch.mockReturnValueOnce(attachment.promise)
    }
    await tick(60_000)
    const pendingStarts = stage === 'authorization' ? 1 : 2
    expect(watch).toHaveBeenCalledTimes(pendingStarts)
    expect(authorize).toHaveBeenCalledTimes(2)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(refresh).toHaveBeenCalledTimes(1)
    await tick(120_000)
    expect(watch).toHaveBeenCalledTimes(pendingStarts)
    expect(authorize).toHaveBeenCalledTimes(2)
    expect(refresh).toHaveBeenCalledTimes(13)
    expect(replacementStop).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(1)
    window.dispatchEvent(new Event('focus'))
    window.dispatchEvent(new Event('pageshow'))
    await flush()
    expect(watch).toHaveBeenCalledTimes(pendingStarts)
    expect(authorize).toHaveBeenCalledTimes(2)
    refresh.mockClear()
    if (stage === 'authorization') authorization.resolve(undefined)
    else attachment.resolve(replacementStop)
    await flush()
    expect(watch).toHaveBeenCalledTimes(2)
    expect(refresh).toHaveBeenCalledTimes(1)
    expect(replacementStop).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(1)
    refresh.mockClear()
    await tick(59_999)
    expect(watch).toHaveBeenCalledTimes(2)
    expect(refresh).not.toHaveBeenCalled()
    await tick(1)
    expect(watch).toHaveBeenCalledTimes(3)
    expect(authorize).toHaveBeenCalledTimes(3)
    expect(refresh).toHaveBeenCalledTimes(2)
    expect(replacementStop).toHaveBeenCalledTimes(1)
  })

  it('continues fallback polling when every watch attempt fails', async () => {
    watch.mockRejectedValue(new Error('still unavailable'))
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    await tick(30_000)
    expect(watch).toHaveBeenCalledTimes(4)
    expect(refresh.mock.calls.length).toBeGreaterThanOrEqual(4)
  })

  it('handles authorization failure before watch and retries the unified authorization', async () => {
    authorize.mockRejectedValueOnce(new Error('scope unavailable'))
    const refresh = vi.fn(async () => {})
    install(refresh)
    await flush()
    expect(watch).not.toHaveBeenCalled()
    expect(refresh).toHaveBeenCalledTimes(1)
    await tick(10_000)
    expect(authorize).toHaveBeenCalledTimes(2)
    expect(watch).toHaveBeenCalledTimes(1)
  })

  it('keeps fallback polling while a watch startup is pending without duplicate starts', async () => {
    const attachment = deferred<UnwatchFn>()
    watch.mockReturnValueOnce(attachment.promise)
    const refresh = vi.fn(async () => {})
    const dispose = install(refresh)
    await tick(30_000)
    expect(watch).toHaveBeenCalledTimes(1)
    expect(refresh).toHaveBeenCalledTimes(3)
    dispose()
    const stop = vi.fn()
    attachment.resolve(stop)
    await flush()
    expect(stop).toHaveBeenCalledTimes(1)
    expect(vi.getTimerCount()).toBe(0)
  })

  it('releases a late watcher immediately after dispose, with no timers or refresh', async () => {
    const attachment = deferred<UnwatchFn>()
    watch.mockReturnValueOnce(attachment.promise)
    const refresh = vi.fn(async () => {})
    const dispose = install(refresh)
    await flush()
    dispose()
    const stop = vi.fn()
    attachment.resolve(stop)
    await flush()
    emit()
    await tick(120_000)
    expect(stop).toHaveBeenCalledTimes(1)
    expect(refresh).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
    expect(perfLog).toHaveBeenCalledWith(expect.stringContaining('late startup'))
  })

  it('does not start watch after dispose during asynchronous authorization', async () => {
    const authorization = deferred<void>()
    authorize.mockReturnValueOnce(authorization.promise)
    const refresh = vi.fn(async () => {})
    const dispose = install(refresh)
    dispose()
    authorization.resolve(undefined)
    await flush()
    expect(watch).not.toHaveBeenCalled()
    expect(refresh).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
  })

  it('ignores a late startup rejection after dispose', async () => {
    const attachment = deferred<UnwatchFn>()
    watch.mockReturnValueOnce(attachment.promise)
    const refresh = vi.fn(async () => {})
    const dispose = install(refresh)
    await flush()
    dispose()
    attachment.reject(new Error('late failure'))
    await tick(120_000)
    expect(perfLog).not.toHaveBeenCalledWith(expect.stringContaining('watch degraded'))
    expect(refresh).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
  })

  it('cleanup is idempotent and removes debounce, polling and all wake listeners', async () => {
    const refresh = vi.fn(async () => {})
    const dispose = install(refresh)
    await flush()
    refresh.mockClear()
    emit()
    dispose()
    dispose()
    window.dispatchEvent(new Event('focus'))
    window.dispatchEvent(new Event('pageshow'))
    changeVisibility('visible')
    await tick(120_000)
    expect(stops[0]).toHaveBeenCalledTimes(1)
    expect(watch).toHaveBeenCalledTimes(1)
    expect(refresh).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
  })

  it('does not run a dirty follow-up when disposed during a scan', async () => {
    const refresh = vi.fn(async () => {})
    const dispose = install(refresh)
    await flush()
    refresh.mockClear()
    const scan = deferred<void>()
    refresh.mockReturnValueOnce(scan.promise)
    emit()
    await tick(300)
    emit()
    dispose()
    scan.resolve(undefined)
    await tick(120_000)
    expect(refresh).toHaveBeenCalledTimes(1)
    expect(vi.getTimerCount()).toBe(0)
  })
})

